async function seedClients() {
    console.log("Connecting to database:", DB_CONFIG.database, "at", DB_CONFIG.host);
    const conn = await mysql.createConnection(DB_CONFIG);

    try {
        console.log(`Starting to seed ${sampleClients.length} clients...`);

        const now = new Date();
        const sql = `
            INSERT INTO clients_data (
                full_name, email, gender, status, phone_number,
                company_name, website_url, country, state, city,
                lead_source, lead_stage, profile_image_url,
                created_at, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        `;

        let insertedCount = 0;
        for (const c of sampleClients) {
            await conn.execute(sql, [
                c.full_name,
                c.email,
                c.gender,
                c.status,
                c.phone_number,
                c.company_name,
                c.website_url,
                c.country,
                c.state,
                c.city,
                c.lead_source,
                c.lead_stage,
                c.profile_image_url,
                now,
                now,
            ]);
            insertedCount++;
        }

        const [rows] = await conn.query("SELECT COUNT(*) as total FROM clients_data");
        console.log(`✅ Successfully inserted ${insertedCount} client seeds!`);
        console.log(`📊 Total clients in DB now: ${rows[0].total}`);
    } catch (err) {
        console.error("❌ Seeding failed:", err.message);
        process.exit(1);
    } finally {
        await conn.end();
    }
}

seedClients();

